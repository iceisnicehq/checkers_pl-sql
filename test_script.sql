--
-- Сначала найдем завершенную игру
DECLARE
    v_game_id NUMBER;
BEGIN
    SELECT game_id INTO v_game_id
    FROM v_ended_games
    WHERE ROWNUM = 1;
    
    IF v_game_id IS NOT NULL THEN
        game_logic.watch_game_replay(p_game_id => v_game_id);
    ELSE
        DBMS_OUTPUT.PUT_LINE('Нет завершенных игр для просмотра реплея');
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('Нет завершенных игр для просмотра реплея');
END;
