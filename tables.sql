-- 2. КОНСТРЕЙНТЫ (PK, FK, UK, CHECK)
-- =============================================================================

-- Primary Keys
ALTER TABLE players ADD CONSTRAINT pk_players PRIMARY KEY (player_id);
ALTER TABLE game_rules ADD CONSTRAINT pk_game_rules PRIMARY KEY (rule_id);
ALTER TABLE games ADD CONSTRAINT pk_games PRIMARY KEY (game_id);
ALTER TABLE game_moves ADD CONSTRAINT pk_game_moves PRIMARY KEY (move_id);
ALTER TABLE audit_log ADD CONSTRAINT pk_audit_log PRIMARY KEY (log_id);
-- Unique Keys
ALTER TABLE players ADD CONSTRAINT uk_players_username UNIQUE (username);
ALTER TABLE game_rules ADD CONSTRAINT uk_game_rules_name UNIQUE (rule_name);
ALTER TABLE game_moves ADD CONSTRAINT uk_game_moves_game_move UNIQUE (game_id, move_number);

-- Foreign Keys
ALTER TABLE games ADD CONSTRAINT fk_games_rule FOREIGN KEY (rule_id) REFERENCES game_rules(rule_id);
ALTER TABLE games ADD CONSTRAINT fk_games_player_white FOREIGN KEY (player_white_id) REFERENCES players(player_id);
ALTER TABLE games ADD CONSTRAINT fk_games_player_black FOREIGN KEY (player_black_id) REFERENCES players(player_id);
ALTER TABLE games ADD CONSTRAINT fk_games_winner FOREIGN KEY (winner_player_id) REFERENCES players(player_id);

ALTER TABLE game_moves ADD CONSTRAINT fk_game_moves_game FOREIGN KEY (game_id) REFERENCES games(game_id) ON DELETE CASCADE;
ALTER TABLE game_moves ADD CONSTRAINT fk_game_moves_player FOREIGN KEY (player_id) REFERENCES players(player_id);

-- Check Constraints
ALTER TABLE games ADD CONSTRAINT chk_games_status CHECK (status IN ('ACTIVE', 'WHITE_WIN', 'BLACK_WIN', 'DRAW', 'TIMEOUT', 'ABORTED'));
ALTER TABLE games ADD CONSTRAINT chk_games_turn CHECK (current_turn IN ('W', 'B'));
ALTER TABLE game_moves ADD CONSTRAINT chk_game_moves_capture CHECK (is_capture IN ('Y', 'N'));
ALTER TABLE game_rules ADD CONSTRAINT chk_game_rules_pos_rep CHECK (enable_pos_repetition_draw IN ('Y', 'N'));


