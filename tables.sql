-- -----------------------------------------------------------------------------
-- PLAYERS: Пользователи системы
-- Хранит информацию об игроках. Запись создается при первом участии в игре.
-- -----------------------------------------------------------------------------
CREATE TABLE players (
    player_id   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    username    VARCHAR2(128) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

COMMENT ON TABLE players IS 'Игроки. Запись создается при создании первой партии пользователем БД.';
COMMENT ON COLUMN players.player_id IS 'Уникальный идентификатор игрока (PK).';
COMMENT ON COLUMN players.username IS 'Имя пользователя Oracle, уникально.';
COMMENT ON COLUMN players.created_at IS 'Дата и время регистрации игрока в системе.';


-- -----------------------------------------------------------------------------
-- GAME_RULES: Справочник правил игры
-- Позволяет в будущем легко добавлять новые варианты шашек (международные и т.д.)
-- -----------------------------------------------------------------------------
CREATE TABLE game_rules (
    rule_id             NUMBER(3) NOT NULL,
    rule_name           VARCHAR2(50) NOT NULL,
    board_size          NUMBER(2) DEFAULT 8 NOT NULL,
    draw_moves_limit    NUMBER(3) DEFAULT 40 NOT NULL, -- Лимит полуходов без взятия для ничьей
    enable_pos_repetition_draw CHAR(1) DEFAULT 'Y' NOT NULL
);

COMMENT ON TABLE game_rules IS 'Справочник правил игры (русские, международные и т.д.).';
COMMENT ON COLUMN game_rules.rule_id IS 'Код правил (PK).';
COMMENT ON COLUMN game_rules.rule_name IS 'Наименование правил.';
COMMENT ON COLUMN game_rules.board_size IS 'Размер доски (8 для русских, 10 для международных).';
COMMENT ON COLUMN game_rules.draw_moves_limit IS 'Количество полуходов без взятий и движения дамок, после которого объявляется ничья.';
COMMENT ON COLUMN game_rules.enable_pos_repetition_draw IS 'Флаг (Y/N), включено ли правило ничьей по троекратному повторению позиции.';


-- -----------------------------------------------------------------------------
-- GAMES: Партии
-- Основная таблица, хранящая состояние текущих и результаты завершенных партий.
-- -----------------------------------------------------------------------------
CREATE TABLE games (
    game_id             NUMBER(12) GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    rule_id             NUMBER(3) DEFAULT 1 NOT NULL, -- По умолчанию "Русские шашки"
    player_white_id     NUMBER(10) NOT NULL,
    player_black_id     NUMBER(10) NOT NULL,
    status              VARCHAR2(20) NOT NULL, -- ACTIVE, WHITE_WIN, BLACK_WIN, DRAW, TIMEOUT, ABORTED
    current_turn        CHAR(1) DEFAULT 'W' NOT NULL, -- 'W' - White, 'B' - Black
    board_position      VARCHAR2(64) NOT NULL, -- Строковое представление позиции на 32/50 игровых полях
    moves_since_capture NUMBER(3) DEFAULT 0 NOT NULL, -- Счетчик ходов без взятия для правила ничьей
    last_move_at        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    winner_player_id    NUMBER(10),
    start_time          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    end_time            TIMESTAMP WITH TIME ZONE,
    time_limit_move_sec NUMBER(4), -- Ограничение времени на ход в секундах
    time_limit_game_sec NUMBER(5)  -- Ограничение времени на всю партию в секундах
);

COMMENT ON TABLE games IS 'Игровые партии и их текущее состояние.';
COMMENT ON COLUMN games.game_id IS 'Уникальный идентификатор партии (PK).';
COMMENT ON COLUMN games.rule_id IS 'Правила, по которым идет игра (FK к game_rules).';
COMMENT ON COLUMN games.player_white_id IS 'ID игрока за белых (FK к players).';
COMMENT ON COLUMN games.player_black_id IS 'ID игрока за черных (FK к players).';
COMMENT ON COLUMN games.status IS 'Текущий статус партии.';
COMMENT ON COLUMN games.current_turn IS 'Чей сейчас ход (W/B).';
COMMENT ON COLUMN games.board_position IS 'Представление доски в виде строки. Для 8x8 - 32 символа, где каждый символ - состояние одного игрового поля (w,b,W,B,_).';
COMMENT ON COLUMN games.moves_since_capture IS 'Счетчик полуходов без взятия для определения ничьей.';
COMMENT ON COLUMN games.last_move_at IS 'Время последнего сделанного хода (для контроля таймаутов).';
COMMENT ON COLUMN games.winner_player_id IS 'ID победившего игрока, если партия завершена победой.';
COMMENT ON COLUMN games.start_time IS 'Время начала партии.';
COMMENT ON COLUMN games.end_time IS 'Время окончания партии.';
COMMENT ON COLUMN games.time_limit_move_sec IS 'Лимит на ход в секундах (параметр партии).';
COMMENT ON COLUMN games.time_limit_game_sec IS 'Лимит на партию в секундах (параметр партии).';


-- -----------------------------------------------------------------------------
-- GAME_MOVES: Протокол ходов партии
-- Хронологическая запись всех ходов в каждой партии.
-- -----------------------------------------------------------------------------
CREATE TABLE game_moves (
    move_id         NUMBER(18) GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    game_id         NUMBER(12) NOT NULL,
    move_number     NUMBER(4) NOT NULL, -- Номер полухода
    player_id       NUMBER(10) NOT NULL,
    move_notation   VARCHAR2(50) NOT NULL, -- Алгебраическая нотация хода (e.g., "c3-d4", "a3:c5:e7")
    is_capture      CHAR(1) DEFAULT 'N' NOT NULL,
    move_timestamp  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

COMMENT ON TABLE game_moves IS 'Протокол ходов всех партий.';
COMMENT ON COLUMN game_moves.move_id IS 'Уникальный ID хода (PK).';
COMMENT ON COLUMN game_moves.game_id IS 'ID партии, к которой относится ход (FK к games).';
COMMENT ON COLUMN game_moves.move_number IS 'Порядковый номер полухода в партии.';
COMMENT ON COLUMN game_moves.player_id IS 'ID игрока, совершившего ход (FK к players).';
COMMENT ON COLUMN game_moves.move_notation IS 'Нотация хода в понятном для человека формате.';
COMMENT ON COLUMN game_moves.is_capture IS 'Флаг (Y/N), был ли ход взятием.';
COMMENT ON COLUMN game_moves.move_timestamp IS 'Точное время совершения хода.';


-- -----------------------------------------------------------------------------
-- AUDIT_LOG: Журнал событий
-- Для записи важных неигровых событий (ошибки валидации, таймауты и т.д.)
-- -----------------------------------------------------------------------------
CREATE TABLE audit_log (
    log_id          NUMBER(18) GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    log_timestamp   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    username        VARCHAR2(128),
    game_id         NUMBER(12),
    event_type      VARCHAR2(50) NOT NULL,
    event_details   VARCHAR2(1000)
);

COMMENT ON TABLE audit_log IS 'Журнал аудита для значимых событий и ошибок.';
COMMENT ON COLUMN audit_log.event_type IS 'Тип события (e.g., GAME_CREATED, INVALID_MOVE, SESSION_TIMEOUT).';
COMMENT ON COLUMN audit_log.event_details IS 'Подробности события.';


